/* The played game's entry for a creature type, or null when it has none. */
static const struct BodyEntry *FindBody(int16_t type)
{
	const struct BodyEntry *table = PlayedGame() == GAME_BG ? BgBodyTable : BodyTable;
	int16_t count = PlayedGame() == GAME_BG ? BG_BODY_COUNT : BODY_COUNT;
	int16_t i;

	for (i = 0; i < count; i++)
		if (table[i].type == type)
			return &table[i];
	return 0;
}

int16_t GetBodyType(int16_t type)
{
	const struct BodyEntry *body = FindBody(type);

	return body ? body->bodyType : 400;
}

int16_t GetBodyFrame(int16_t type)
{
	const struct BodyEntry *body = FindBody(type);

	return body ? body->bodyFrame : 0;
}

int16_t GetMeatFrame(uint16_t type)
{
	int16_t frame = MeatFrame(type);

	return frame >= 0 ? frame : GenerateRandomIntegerInRange(32);
}
